/// Si hasta las variantes se acaban: un SizedBox con su propia altura, que
/// nunca se repite.
Persona sizedBoxDe(int altura) => Persona(
      'SizedBox(height: $altura)',
      'Sabes exactamente cuánto espacio ocupar: $altura píxeles, ni uno más.',
      'Una caja de tamaño fijo. Esta mide $altura píxeles de alto.',
    );

final _sizedBox = RegExp(r'^SizedBox\(height: (\d{1,5})\)$');

/// La persona que corresponde a un apodo que el celular ya tenía (por
/// ejemplo, si el servidor se reinició). Null si no es un apodo válido.
Persona? personaDe(Object? widget) {
  if (widget is! String) return null;
  for (final persona in [...personas, ...variantes]) {
    if (persona.widget == widget) return persona;
  }
  final altura = _sizedBox.firstMatch(widget)?.group(1);
  return altura == null ? null : sizedBoxDe(int.parse(altura));
}
